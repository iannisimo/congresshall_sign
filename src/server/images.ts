import { readFileSync } from 'node:fs';
import sharp, { type Sharp } from 'sharp';
import type { LogoCrop } from '../shared/schemas.ts';
import { ApiError } from './http.ts';

export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
const MAX_SIDE = 512;
const ACCEPTED = new Set(['png', 'jpeg', 'webp', 'gif', 'svg', 'avif', 'tiff']);

export interface NormalizedLogo {
  mime: 'image/png';
  data: Uint8Array;
  width: number;
  height: number;
}

/** Longest side images are brought to before cropping, so zooming far out stays cheap. */
const CROP_SOURCE_SIDE = 2048;

/** The square `crop` of an image, padded with transparency where it reaches past the edges. */
async function cropSquare(image: Sharp, crop: LogoCrop) {
  const { data, info } = await image
    .resize({ width: CROP_SOURCE_SIDE, height: CROP_SOURCE_SIDE, fit: 'inside', withoutEnlargement: true })
    .png()
    .toBuffer({ resolveWithObject: true });
  const left = Math.round(crop.left * info.width);
  const top = Math.round(crop.top * info.height);
  const side = Math.max(1, Math.round(crop.size * info.width));
  const pad = {
    left: Math.max(0, -left),
    top: Math.max(0, -top),
    right: Math.max(0, left + side - info.width),
    bottom: Math.max(0, top + side - info.height),
  };
  const padded = await sharp(data)
    .extend({ ...pad, background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .toBuffer();
  return sharp(padded).extract({ left: left + pad.left, top: top + pad.top, width: side, height: side });
}

/**
 * Turns any accepted image into a PNG of at most 512 px per side. With a `crop` (chosen in the admin
 * area) it keeps that square; otherwise uniform borders are trimmed so logos fill their box on the sign. PNG works on every browser a smart TV may have; rasterizing SVG also
 * removes any script it may contain.
 */
export async function normalizeLogo(input: Uint8Array, crop?: LogoCrop): Promise<NormalizedLogo> {
  let format: string | undefined;
  let width = 0;
  let height = 0;
  try {
    ({ format, width, height } = await sharp(input).metadata());
  } catch {
    throw new ApiError(400, 'Il file non è un’immagine valida');
  }
  if (!format || !ACCEPTED.has(format)) throw new ApiError(400, 'Formato non supportato: usa PNG, JPEG, WebP, GIF o SVG');

  // Rasterize vectors big enough to downscale cleanly.
  const density = format === 'svg' ? Math.min(2400, Math.max(72, (72 * MAX_SIDE * 2) / Math.max(width, height, 1))) : undefined;
  const pipeline = async (trim: boolean) => {
    let image = sharp(input, { density, limitInputPixels: 50_000_000 }).rotate();
    if (crop) image = await cropSquare(image, crop);
    else if (trim) image = image.trim({ threshold: 10 });
    return image
      .resize({ width: MAX_SIDE, height: MAX_SIDE, fit: 'inside', withoutEnlargement: true })
      .png({ compressionLevel: 9, adaptiveFiltering: true })
      .toBuffer({ resolveWithObject: true });
  };

  try {
    // Trimming fails on images that are a single colour; keep those as they are.
    const { data, info } = await pipeline(true).catch(() => pipeline(false));
    return { mime: 'image/png', data, width: info.width, height: info.height };
  } catch {
    throw new ApiError(400, 'Impossibile elaborare l’immagine');
  }
}

// Generic emblems any organizer can use (generated by scripts/generate-generic-logos.mjs; Lucide icons,
// license next to them).
const GENERIC_DIR = new URL('./generic-logos/', import.meta.url);
export interface GenericLogo {
  id: string;
  name: string;
}
export const GENERIC_LOGOS = JSON.parse(readFileSync(new URL('catalog.json', GENERIC_DIR), 'utf8')) as GenericLogo[];

export function readGenericLogo(id: string): Buffer | undefined {
  if (!GENERIC_LOGOS.some((logo) => logo.id === id)) return undefined;
  return readFileSync(new URL(`${id}.svg`, GENERIC_DIR));
}

/** Downloads an image for the admin, instead of going through a third-party proxy. */
export async function fetchImage(url: string): Promise<Uint8Array> {
  let response: Response;
  try {
    response = await fetch(url, {
      signal: AbortSignal.timeout(10_000),
      headers: { Accept: 'image/*', 'User-Agent': 'congresshall-sign' },
    });
  } catch {
    throw new ApiError(400, 'Immagine non raggiungibile');
  }
  if (!response.ok || !response.body) throw new ApiError(400, `Immagine non raggiungibile (HTTP ${response.status})`);
  if (Number(response.headers.get('content-length') ?? 0) > MAX_UPLOAD_BYTES) throw new ApiError(413, 'Immagine troppo grande (max 10 MB)');

  const chunks: Uint8Array[] = [];
  let size = 0;
  for await (const chunk of response.body) {
    size += chunk.byteLength;
    if (size > MAX_UPLOAD_BYTES) throw new ApiError(413, 'Immagine troppo grande (max 10 MB)');
    chunks.push(chunk);
  }
  return Buffer.concat(chunks);
}
